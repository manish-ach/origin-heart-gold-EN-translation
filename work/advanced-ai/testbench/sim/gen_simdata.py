"""The hack's battle data as C tables for the simulator (sim/) and the host build of the advanced AI.

  .venv/bin/python work/advanced-ai/testbench/sim/gen_simdata.py [--rom ROM] [--out DIR]
                                                                  [--extra-teams FILE | --no-extra-teams]

Writes DIR/simdata.c and DIR/sim_ids.h (default: simbuild.build_dir(ROM), work/build/advanced-ai/sim/<ROM name>), all
from the ROM under test (default: the untouched Chinese hack). The Makefile runs it (simbuild.build(rom) makes the
simulator for a ROM):
- species `a/0/0/2`: base stats in the ROM's order (HP Atk Def Spe SpA SpD), types, the two abilities and the hidden
  one, the gender ratio, and whether it evolves (`a/0/3/4`, for Eviolite);
- moves `extra/new_move_data.narc` decoded field by field (lib/aidata.py documents the 40-byte Gen 5 record), plus
  the raw records and WAZADATA_GetParam's parameter map that the AI's move getter reads (hostai/gen_data.py);
- the engine's type chart (overlay 14, 0x0224DA40);
- items: whether the battle engine's item handler table has the id (an item without an entry does nothing, such as the
  Rocky Helmet 324 trainers hold), the type a type-boosting item powers up, the type a resist berry halves;
- every six-Pokemon trainer team versus/aiteams.py builds (the pool aivsai draws from), with each set's EVs in the
  game's order (HP Atk Def Spe SpA SpD), its nature and its IV; then the extra teams of DIR/extra_teams.json, if any
  (pool 2: aivsai's random teams, a JSON list of aiteams.random_team objects; nature Hardy, IV 31 and EV 0 where a
  set gives none, as the DS's injector builds them). --extra-teams FILE copies FILE there, --no-extra-teams removes
  it; the Makefile's rerun keeps it, and run.py and turnlog.py match logs against the same list (all_teams);
- each species' weight from the Pokedex text (bank 800: species 1-493; the hack's own text, from the workspace bank
  work/translate/banks/a027/0800.json, which the English build copies unchanged);
- names of species, moves, abilities and items (for the logs), and sim_ids.h: S_/M_/A_/I_ constants for every name
  (lib/names.json's frozen names, so the constants the C code uses are the same for every ROM).
The AI's own ids come from the frozen src/ids.h. The Makefile reruns this when this file or the ROM changes.
"""
import argparse
import os
import re
import struct
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'lib'))
import tbpaths  # noqa: E402

import ndspy.rom  # noqa: E402

import aicalc  # noqa: E402
import aiteams  # noqa: E402
import gen_data  # noqa: E402  (hostai/: the AI's move getter map and record dump)
import simbuild  # noqa: E402
from aidata import NATURES, STATS, norm  # noqa: E402

MIN_LEVEL = 80          # aivsai.draw_scenarios: trainer teams whose six are all at this level or above in the ROM
POOL_RANDOM = 2


def extra_path(rom=simbuild.DEFAULT_ROM):
    """The extra teams of a ROM's simulator build (--extra-teams copies them there)."""
    return os.path.join(simbuild.build_dir(rom), 'extra_teams.json')


def extra_teams(path):
    import json
    if not os.path.exists(path):
        return []
    out = json.load(open(path, encoding='utf-8'))
    for t in out:
        for s in t['team']:
            s.setdefault('nature', 'Hardy')
            s.setdefault('ivs', 31)
            s.setdefault('evs', {k: 0 for k in STATS})
    return out


def all_teams(rom=simbuild.DEFAULT_ROM):
    """The simulator's team list in its index order: the six-Pokemon trainer teams, then the extra teams."""
    return aiteams.trainer_teams(rom, 6) + extra_teams(extra_path(rom))


def cstr(s):
    return '"%s"' % s.replace('\\', '\\\\').replace('"', '\\"')


def ident(name):
    return re.sub(r'[^A-Z0-9]', '_', norm(name).upper()) or 'NONE'


def s8(b):
    return b - 256 if b > 127 else b


def move_row(r):
    hits = r[7]
    return '{%s}' % ','.join(str(v) for v in (
        r[0], r[1], r[2], r[3], r[4], r[5], s8(r[6]), (hits & 15) if hits else 1, (hits >> 4) if hits else 1,
        r[8] | r[9] << 8, r[10], r[11], r[12], r[13], r[14], r[15], r[16] | r[17] << 8, s8(r[18]), s8(r[19]), r[20],
        '{%d,%d,%d}' % tuple(r[21:24]), '{%d,%d,%d}' % tuple(s8(x) for x in r[24:27]), '{%d,%d,%d}' % tuple(r[27:30]),
        '%du' % struct.unpack_from('<I', r, 32)[0]))


def ids_header(d):
    out = ['/* Generated by sim/gen_simdata.py: do not edit. */', '#ifndef SIM_IDS_H', '#define SIM_IDS_H']
    for prefix, names, limit in (('S_', d.species_name, len(d.personal)), ('M_', d.move_name, len(d.moves)),
                                 ('A_', d.ability_name, 1 << 16), ('I_', d.item_name, 1 << 16)):
        seen = {}
        for i in sorted(names):
            if i >= limit or not names[i]:
                continue
            key = prefix + ident(names[i])
            # a name given to two ids: the one aidata resolves (for items the later id, which the engine handles)
            kind = {'S_': 'species', 'M_': 'move', 'A_': 'ability', 'I_': 'item'}[prefix]
            try:
                want = d.id(kind, names[i])
            except KeyError:
                want = i
            if key in seen and want != i:
                continue
            seen[key] = i
        out += ['#define %s %d' % (k, v) for k, v in sorted(seen.items(), key=lambda kv: kv[1])]
    out.append('#endif')
    return '\n'.join(out) + '\n'


def weights(n):
    """Each species' weight in tenths of a kilogram from the Pokedex text (bank 800, species 1-493; 0 unknown: the
    species after 493 have no Pokedex entry in this ROM)."""
    import json
    bank = json.load(open(os.path.join(tbpaths.WORK, 'translate', 'banks', 'a027', '0800.json'), encoding='utf-8'))
    bank = [s['zh'] for s in bank['strings']]
    out = [0] * n
    for i, t in enumerate(bank[:n]):
        t = ''.join(chr(ord(c) - 0xFEE0) if '\uff01' <= c <= '\uff5e' else c for c in t.replace('{U:01FB}', ''))
        m = re.match(r'\s*(\d+)\.(\d)\s*kg', t)
        if i and m:
            out[i] = int(m.group(1)) * 10 + int(m.group(2))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--rom', default=simbuild.DEFAULT_ROM)
    ap.add_argument('--out', help='default: simbuild.build_dir(ROM)')
    g = ap.add_mutually_exclusive_group()
    g.add_argument('--extra-teams', help='a JSON list of teams to append (copied to OUT/extra_teams.json)')
    g.add_argument('--no-extra-teams', action='store_true')
    a = ap.parse_args()
    a.out = a.out or simbuild.build_dir(a.rom)
    os.makedirs(a.out, exist_ok=True)
    extra = os.path.join(a.out, 'extra_teams.json')
    if a.extra_teams:
        import shutil
        shutil.copyfile(a.extra_teams, extra)
    elif a.no_extra_teams and os.path.exists(extra):
        os.remove(extra)
    d = aiteams.data(a.rom)
    handled = aiteams.rom_tables(a.rom)['handled_items']
    rom = ndspy.rom.NintendoDSRom.fromFile(a.rom)
    nitems = max(d.item_name) + 1
    src = ['/* Generated by sim/gen_simdata.py from %s: do not edit. */' % os.path.basename(a.rom),
           '#include "sim.h"']

    rows = []
    for i, r in enumerate(d.personal):
        ab = [struct.unpack_from('<H', r, o)[0] for o in (0x16, 0x18, 0x1A)]
        rows.append('{{%s},{%d,%d},{%d,%d,%d},%d,%d}' % (','.join(str(x) for x in r[0:6]), r[6], r[7], ab[0], ab[1], ab[2],
                                                          r[0x10], int(d.evolves(i)) if i else 0))
    src.append('const SpeciesRec sim_species[%d] = {\n%s};' % (len(rows), ',\n'.join(rows)))
    src.append('const int sim_nspecies = %d;' % len(rows))
    w = weights(len(rows))
    src.append('const u16 sim_weight[%d] = {%s};' % (len(w), ','.join(map(str, w))))
    src.append('const MoveRec sim_moves[%d] = {\n%s};' % (len(d.moves), ',\n'.join(move_row(r) for r in d.moves)))
    src.append('const int sim_nmoves = %d;' % len(d.moves))
    src.append('const u8 sim_chart[18][18] = {%s};' % ','.join('{%s}' % ','.join(str(v) for v in row) for row in d.chart))

    boost = [0] * nitems
    resist = [0] * nitems
    for name, t in aicalc.TYPE_ITEMS.items():
        boost[d.id('item', name)] = t + 1
    for name, t in aicalc.RESIST_BERRIES.items():
        resist[d.id('item', name)] = t + 1
    src.append('const int sim_nitems = %d;' % nitems)
    src.append('const u8 sim_item_handled[%d] = {%s};' % (nitems, ','.join('1' if i in handled else '0' for i in range(nitems))))
    src.append('const u8 sim_item_boost[%d] = {%s};' % (nitems, ','.join(map(str, boost))))
    src.append('const u8 sim_item_resist[%d] = {%s};' % (nitems, ','.join(map(str, resist))))

    teams = aiteams.trainer_teams(a.rom, 6)
    ntrainer = len(teams)
    teams += extra_teams(extra)
    trows = []
    for t in teams:
        sets = []
        for s in t['team']:
            mv = [d.id('move', m) for m in s['moves']] + [0] * (4 - len(s['moves']))
            sets.append('{%d,%d,%d,{%s},%d,%d,%d,{%s}}' % (
                d.id('species', s['species']), d.id('ability', s['ability']), d.id('item', s['item']) if s['item'] else 0,
                ','.join(map(str, mv)), s['level'], NATURES.index(s['nature']), s['ivs'],
                ','.join(str(s['evs'][k]) for k in STATS)))
        pool = POOL_RANDOM if t.get('source') == 'random' else int(min(s['level'] for s in t['team']) >= MIN_LEVEL)
        trows.append('{%d,%s,%d,%d,{%s}}' % (t.get('trainer', 0), cstr(t['name']), len(t['team']), int(pool), ','.join(sets)))
    src.append('const TeamRec sim_teams[%d] = {\n%s};' % (len(trows), ',\n'.join(trows)))
    src.append('const int sim_nteams = %d;' % len(trows))

    for kind, names, n in (('species', d.species_name, len(d.personal)), ('move', d.move_name, len(d.moves)),
                           ('ability', d.ability_name, max(d.ability_name) + 1), ('item', d.item_name, nitems)):
        src.append('const char *const sim_%s_name[%d] = {%s};' % (kind, n, ','.join(cstr(names.get(i, '')) for i in range(n))))
    src.append('const int sim_nabilities = %d;' % (max(d.ability_name) + 1))

    # the AI's view of the move data (tools/hostai/engine.c reads these names)
    pm = gen_data.param_map(rom)
    src += ['const int host_nmoves = %d;' % len(d.moves), gen_data.c_bytes('host_moves', d.moves, 40),
            'const unsigned char host_waza_param[%d][3] = {%s};' % (gen_data.NPARAMS, ','.join('{%d,%d,%d}' % p for p in pm)),
            'const unsigned char host_chart[324] = {%s};' % ','.join(str(v) for row in d.chart for v in row)]

    with open(os.path.join(a.out, 'simdata.c'), 'w') as f:
        f.write('\n'.join(src) + '\n')
    with open(os.path.join(a.out, 'sim_ids.h'), 'w') as f:
        f.write(ids_header(d))
    print('species %d, moves %d, items %d (%d handled), teams %d (%d in the level-%d pool, %d extra) -> %s' % (
        len(d.personal), len(d.moves), nitems, len(handled), ntrainer,
        sum(1 for t in teams[:ntrainer] if min(s['level'] for s in t['team']) >= MIN_LEVEL), MIN_LEVEL,
        len(teams) - ntrainer, a.out))


if __name__ == '__main__':
    main()
