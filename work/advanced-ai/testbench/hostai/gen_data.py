"""The ROM data the host build of the advanced AI needs, as C: DIR/hostdata.c.

  .venv/bin/python work/advanced-ai/testbench/hostai/gen_data.py --rom ROM --out DIR

The Makefile runs it (DIR is the build directory of that ROM).

- the move records (`extra/new_move_data.narc`, 40 bytes each) and the move getter's parameter map, decoded from
  WAZADATA_GetParam's jump table (arm9 0x0201A2E0, params 0-0x52): each case is a byte, a signed byte, a halfword,
  a nibble of byte 7, or one bit of the words at +0x20/+0x24;
- the engine's type chart (overlay 14 at 0x0224DA40).
The AI's ids come from the frozen src/ids.h, not from here.
"""
import argparse
import os
import struct
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'lib'))
import tbpaths  # noqa: E402,F401

import ndspy.rom  # noqa: E402
from capstone import CS_ARCH_ARM, CS_MODE_THUMB, Cs  # noqa: E402

GETTER = 0x0201A2E0
NPARAMS = 0x53
P_ZERO, P_U8, P_S8, P_U16, P_LO4, P_HI4, P_BIT = range(7)


def arm9_reader(rom):
    arm9 = bytes(rom.arm9)
    base = rom.arm9RamAddress
    return lambda a, n: arm9[a - base:a - base + n]


def decode_case(rd, md, addr):
    """(kind, offset, bit) of the getter case at addr."""
    ins = list(md.disasm(rd(addr, 12), addr))
    m0, op0 = ins[0].mnemonic, ins[0].op_str
    off = lambda s: int(s.split('#')[1].rstrip(']'), 16) if '#' in s else 0
    if m0 == 'ldrb' and op0.startswith('r2'):
        return P_U8, off(op0), 0
    if m0 == 'ldrh' and op0.startswith('r2'):
        return P_U16, off(op0), 0
    if m0 == 'movs' and ins[1].mnemonic == 'ldrsb':
        return P_S8, int(op0.split('#')[1], 16), 0
    if m0 == 'ldrb' and op0.startswith('r0') and ins[1].mnemonic == 'lsls':
        sh = int(ins[1].op_str.split('#')[1], 16)
        return (P_LO4 if sh == 0x1C else P_HI4), off(op0), 0
    if m0 == 'ldr' and op0.startswith('r0, [r0'):
        if ins[1].mnemonic == 'lsrs':          # lsrs #0x1f alone: bit 31
            return P_BIT, off(op0), 31
        sh = int(ins[1].op_str.split('#')[1], 16)
        assert ins[2].mnemonic == 'lsrs' and ins[2].op_str.endswith('#0x1f'), ins
        return P_BIT, off(op0), 31 - sh
    if m0 == 'adds' and op0 == 'r0, r2, #0':
        return P_ZERO, 0, 0
    raise ValueError('unknown getter case at %08X: %s %s' % (addr, m0, op0))


def param_map(rom):
    rd = arm9_reader(rom)
    md = Cs(CS_ARCH_ARM, CS_MODE_THUMB)
    table = 0x0201A2F4          # after `add r1, pc` (pc 0x0201A2EE) and `ldrh r1, [r1, #6]`
    out = []
    for p in range(NPARAMS):
        rel = struct.unpack('<h', rd(table + 2 * p, 2))[0]
        out.append(decode_case(rd, md, 0x0201A2F6 + rel))      # `add pc, r1` at 0x0201A2F2: pc = 0x0201A2F6
    return out


def c_bytes(name, rows, width):
    lines = ['const unsigned char %s[%d][%d] = {' % (name, len(rows), width)]
    for r in rows:
        r = bytes(r[:width]).ljust(width, b'\0')
        lines.append('    {%s},' % ','.join(str(b) for b in r))
    return '\n'.join(lines + ['};'])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--rom', required=True)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    from aidata import Data
    rom = ndspy.rom.NintendoDSRom.fromFile(a.rom)
    d = Data(a.rom)
    pm = param_map(rom)
    src = ['/* Generated by hostai/gen_data.py from %s: do not edit. */' % os.path.basename(a.rom),
           'const int host_nmoves = %d;' % len(d.moves),
           c_bytes('host_moves', d.moves, 40),
           'const unsigned char host_waza_param[%d][3] = {%s};' % (NPARAMS, ','.join('{%d,%d,%d}' % p for p in pm)),
           'const unsigned char host_chart[324] = {%s};' % ','.join(str(v) for row in d.chart for v in row)]
    with open(os.path.join(a.out, 'hostdata.c'), 'w') as f:
        f.write('\n'.join(src) + '\n')
    print('moves %d, params %d, chart 324 -> %s' % (len(d.moves), NPARAMS, a.out))


if __name__ == '__main__':
    main()
