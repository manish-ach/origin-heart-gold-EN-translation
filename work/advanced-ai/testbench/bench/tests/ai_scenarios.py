def _load_batches():
    """tests/ai_batches/batch_NN.py, each a SCENARIOS list written by an author who never sees the AI."""
    import glob
    import importlib.util
    import os
    here = os.path.dirname(os.path.abspath(__file__))
    paths = sorted(glob.glob(os.path.join(here, 'ai_batches', 'batch_[0-9][0-9].py')))
    # batches still being written (draft_NN*.py, one per author) load only when named, so other runs never
    # see them half done; several are separated by ':'
    for draft in filter(None, os.environ.get('AI_BATCH_DRAFT', '').split(os.pathsep)):
        paths.append(os.path.abspath(draft))
    for path in paths:
        n = int(os.path.basename(path)[6:8])
        spec = importlib.util.spec_from_file_location('ai_batch_%02d' % n, path)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        for sc in mod.SCENARIOS:
            sc['batch'] = n
            SCENARIOS.append(sc)


_load_batches()
